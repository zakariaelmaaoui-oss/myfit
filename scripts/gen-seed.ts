// Generates supabase/seed.sql (reference foods + recipes) from the same data the app ships with.
// Run: npx vite-node scripts/gen-seed.ts
import { writeFileSync } from 'node:fs';
import foods from '../src/data/foods.json';
import { RECIPES } from '../src/data/recipes';

const q = (v: any) => v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const j = (v: any) => v === undefined || v === null ? 'null' : `${q(JSON.stringify(v))}::jsonb`;
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;
let sql = '-- Generated by scripts/gen-seed.ts — reference data (USDA FoodData Central SR Legacy + MyFit recipe database)\nbegin;\n';
sql += 'delete from public.recipe_ingredients; delete from public.recipes; delete from public.food_nutrients; delete from public.foods;\n';
for (const f of foods as any[]) {
  sql += `insert into public.foods (id, fdc_id, category, name_en, name_fr, name_ar, usda_description, source, added_sugar_basis, portions) values (${q(f.id)}, ${q(f.fdcId)}, ${q(f.category)}, ${q(f.name.en)}, ${q(f.name.fr)}, ${q(f.name.ar)}, ${q(f.usdaDescription)}, ${q(f.source)}, ${q(f.addedSugarBasis)}, ${j(f.portions)});\n`;
  const n = f.per100g;
  sql += `insert into public.food_nutrients values (${q(f.id)}, ${q(n.kcal)}, ${q(n.protein)}, ${q(n.carbs)}, ${q(n.fat)}, ${q(n.fiber)}, ${q(n.sugar)}, ${q(n.addedSugar)}, ${q(n.sodium)});\n`;
}
const ordered = [...RECIPES.filter(r => !r.variantOf), ...RECIPES.filter(r => r.variantOf)];
for (const r of ordered) {
  sql += `insert into public.recipes (id, name, moroccan, kind, meals, servings, serving, prep_min, cook_min, budget, variant_of, variant, note, steps) values (${q(r.id)}, ${j(r.name)}, ${q(r.moroccan)}, ${q(r.kind)}, ${arr(r.meals)}, ${r.servings}, ${j(r.serving)}, ${r.prepMin}, ${r.cookMin}, ${q(!!r.budget)}, ${q(r.variantOf ?? null)}, ${j(r.variant)}, ${j(r.note)}, ${j(r.steps)});\n`;
  r.ingredients.forEach((i, k) => { sql += `insert into public.recipe_ingredients values (${q(r.id)}, ${k}, ${q(i.foodId)}, ${i.grams}, ${q(i.consumed !== false)});\n`; });
}
sql += 'commit;\n';
writeFileSync('supabase/seed.sql', sql);
console.log(`seed.sql: ${(foods as any[]).length} foods, ${RECIPES.length} recipes`);
